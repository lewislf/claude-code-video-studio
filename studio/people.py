"""The real person (approved geometric character), memory pictures and memory orbs.

The art comes from people_svg.json, generated by the sua-mente example's generator script from the canvas sketch, then with keys
and ids translated to English (do not edit the JSON by hand). Two variants of the SAME person: "home" (hoodie, jeans) and
"work" (shirt, tie, badge). Poses "sitting" and "standing".
turn: 0 = facing front; >= 15 uses the version turned ~30 degrees to the right (default 25, like the old profile character).

    from people import *
    svg = person("X-g", "home", "sitting")         # local box ~ x -150..190, top of the head when standing y ~ -540, feet at y=0
    js += person_idle("X-g", dur)                  # breathes, blinks, sways the head

Ids: {p} (root), {p}-body, {p}-legs, {p}-tor (trunk), {p}-torso (trunk path), {p}-armL, {p}-arm (arm on the right side of the
screen, pivot at the shoulder: data-pivot and ANCHORS[...]["shoulder_arm"]), {p}-headW > {p}-head > {p}-eye (both eyes).
{p}-headW carries transform="translate(0 0)" (identity): the sua-mente builds g3/g5/g7 look for this attribute to nest the group,
and since it is the identity GSAP can overwrite it without moving the head (GOTCHAS 1).
Recoloring: each piece uses a base hex (SKIN, HAIR, HOME/WORK torso, pants, shoe); shadow and light are neutral layers
with opacity on top, so .replace(base_hex, new) recolors the whole piece.
"""
import json
import os
import re

_D = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "people_svg.json"), encoding="utf-8"))

SKIN, SKIN_SHADE = "#e0a17a", "#b26e66"  # SKIN_SHADE does not appear in the SVG (shadow became a neutral layer); kept for compatibility
HAIR = "#5b3523"
# torso2: torso shadow tone, informative (does not appear literally in the SVG). sole: the sole's own hex.
HOME = dict(torso="#7b55d8", torso2="#5437a6", pants="#3f61aa", shoe="#e6e0f8", sole="#fbf9ff", head="home")
WORK = dict(torso="#cdd4ec", torso2="#959bc8", pants="#3a3558", shoe="#4a3036", sole="#1c1015", head="work")
TIE = "#a3305f"
RIM = {"home": "#ff4fa3", "work": "#5ee6ff"}

ANCHORS = {}
for _k, _v in _D.items():
    _var, _pose, _g = _k.split("|")
    ANCHORS[(_var, _pose, int(_g))] = {n: (tuple(p) if p else None) for n, p in _v["anc"].items()}


def _key(variant, pose, turn):
    return ("home" if variant == "home" else "work", "standing" if pose == "standing" else "sitting", 30 if turn >= 15 else 0)


def _rim_filter(p, color):
    """Neon glow on the right edge of the silhouette (same as the sketch: silhouette minus itself shifted, blurred)."""
    return (f'<filter id="{p}-rim" x="-30%" y="-15%" width="160%" height="130%" color-interpolation-filters="sRGB">'
            f'<feOffset in="SourceAlpha" dx="-3.7" dy="0" result="d"/><feComposite in="SourceAlpha" in2="d" operator="out" result="b"/>'
            f'<feFlood flood-color="{color}" flood-opacity=".9"/><feComposite in2="b" operator="in"/><feGaussianBlur stdDeviation="5.2" result="g"/>'
            f'<feMerge><feMergeNode in="g"/><feMergeNode in="SourceGraphic"/></feMerge></filter>')


def person(p, variant="home", pose="sitting", glow=None, chair=True, shadow=True, turn=25):
    k = _key(variant, pose, turn)
    d = _D["|".join(map(str, k))]
    frag = d["svg"]
    if not chair:
        frag = re.sub(r"<!--chair-->.*?<!--/chair-->", "", frag, flags=re.S)
    frag = frag.replace("@P@", p)
    sa = ANCHORS[k]["shoulder_arm"]
    # data-pivot before the id and an invisible guide path with a stroke: sua-mente's g5 human(cel=True) reads the arm color by
    # regex and must not match the non-greedy '<g id="{p}-arm">...</g>' (the new arm has nested groups and the swap would break the SVG)
    arm_color = (HOME if k[0] == "home" else WORK)["torso"]
    frag = frag.replace(f'<g id="{p}-arm">', f'<g data-pivot="{sa[0]} {sa[1]}" id="{p}-arm"><path d="M0 0" stroke="{arm_color}" fill="none" stroke-opacity="0"/>', 1)
    defs = d["defs"].replace("@P@", p) + _rim_filter(p, RIM[k[0]])
    rx = 125 if k[1] == "sitting" else 88
    shadow_svg = f'<ellipse cx="0" cy="0" rx="{rx}" ry="12" fill="#06021a" opacity=".55"/>' if shadow else ""
    return f'<g id="{p}"><defs>{defs}</defs>{shadow_svg}<g id="{p}-body" filter="url(#{p}-rim)">{frag}</g></g>'


def head(p, v):
    """Just the new head (standing, turned right), fitted into the old head's local box (x 110..300, y 28..252).
    Ids: {p}-head and {p}-eye."""
    var = "home" if v.get("head", "home") == "home" else "work"
    d = _D[f"{var}|standing|30"]
    s = d["svg"]
    i = s.index('<g id="@P@-head">')
    depth, j = 0, i
    for m in re.finditer(r"<g\b|</g>", s[i:]):
        depth += 1 if m.group(0) != "</g>" else -1
        if depth == 0:
            j = i + m.end()
            break
    hd = s[i:j].replace("@P@", p)
    used = set(re.findall(r"url\(#@P@-(k\d+)\)", s[i:j]))
    defs = "".join(m.group(0) for m in re.finditer(r'<clipPath id="@P@-(k\d+)".*?</clipPath>', d["defs"]) if m.group(1) in used)
    cx, cy = d["anc"]["head_center"]
    sc = 2.2
    return (f'<g transform="translate(205 150) scale({sc}) translate({-cx} {-cy})"><defs>{defs.replace("@P@", p)}</defs>{hd}</g>')


def limb(a, b, width, color):
    return f'<path d="M {a[0]} {a[1]} L {b[0]} {b[1]}" stroke="{color}" stroke-width="{width}" stroke-linecap="round" fill="none"/>'


def person_idle(p, dur, blinks=(2.0, 5.3, 8.8, 12.1, 16.4, 20.2)):
    """JS: trunk breathing, head sway and blinks, deterministic."""
    # svgOrigin at the feet: the drawing's M-9999 cutouts make getBBox huge and "50% 100%" threw the trunk ~120 px up
    js = (f'tl.fromTo("#{p}-tor",{{scaleY:1,svgOrigin:"0 0"}},{{scaleY:1.006,svgOrigin:"0 0",duration:1.7,repeat:{max(1, int(dur / 1.7))},yoyo:true,ease:"sine.inOut"}},0);')
    js += (f'tl.fromTo("#{p}-headW",{{y:0}},{{y:-3,duration:1.7,repeat:{max(1, int(dur / 1.7))},yoyo:true,ease:"sine.inOut"}},0.2);')
    for t in blinks:
        if t < dur - 0.3:
            js += f'tl.fromTo("#{p}-eye",{{scaleY:1,transformOrigin:"50% 50%"}},{{scaleY:0.08,transformOrigin:"50% 50%",duration:0.09,repeat:1,yoyo:true,immediateRender:false}},{t});'
    return js


